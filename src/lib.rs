/// Test harness for formal verification.
#[cfg(kani)]
mod kani_harness {
    use super::*;
    use ::kani;

    /// Largest possible Space Packet, in bytes: a primary header followed by a data field of
    /// `u16::MAX + 1` bytes.
    const MAX_PACKET_LENGTH: usize = u16::MAX as usize + 7;

    /// This test verifies that byte slices of any length up to and beyond the maximum packet size
    /// may be parsed without panics, and that any successfully parsed packet is consistent with
    /// its header. Note that only the header bytes are symbolic. This is needed to restrict the
    /// search space for kani, and is a valid assumption because the parsing implementation never
    /// touches the packet data field contents.
    #[kani::proof]
    fn packet_parsing() {
        let mut bytes = [0u8; MAX_PACKET_LENGTH + 1];
        for byte in &mut bytes[..6] {
            *byte = kani::any();
        }
        let length: usize = kani::any();
        kani::assume(length <= bytes.len());
        let bytes = &bytes[..length];

        match SpacePacket::parse_prefix(bytes) {
            Ok((packet, remainder)) => {
                assert_eq!(
                    packet.packet_data_field().len(),
                    packet.packet_data_length()
                );
                assert_eq!(packet.packet_length() + remainder.len(), length);
                assert!(packet.validate().is_ok());
            }
            Err(InvalidSpacePacket::SliceTooSmallForSpacePacketHeader { length: reported }) => {
                assert!(length < 6);
                assert_eq!(reported, length);
            }
            Err(InvalidSpacePacket::PartialPacket {
                packet_size,
                buffer_size,
            }) => {
                assert!(packet_size > buffer_size);
                assert_eq!(buffer_size, length);
            }
            Err(_) => assert!(length >= 6),
        }
    }

    /// This test verifies that header parsing accepts exactly those headers that are of a
    /// supported version and are not idle packets with a secondary header.
    #[kani::proof]
    fn header_parsing() {
        let bytes: [u8; 6] = kani::any();
        let version = bytes[0] >> 5;
        let secondary_header = bytes[0] & 0x08 != 0;
        let idle = (bytes[0] & 0x07) == 0x07 && bytes[1] == 0xff;

        let valid = version == 0 && !(idle && secondary_header);
        assert_eq!(SpacePacketPrimaryHeader::parse(&bytes).is_ok(), valid);
    }

    /// This test verifies that each primary header setter changes only its own field, for any
    /// initial header contents.
    #[kani::proof]
    fn header_setters_are_independent() {
        let mut header = SpacePacketPrimaryHeader::read_from_bytes(&kani::any::<[u8; 6]>())
            .unwrap_or_else(|_| unreachable!());
        let original = header;

        match kani::any::<u8>() % 5 {
            0 => {
                let packet_type = kani::any();
                header.set_packet_type(packet_type);
                assert_eq!(header.packet_type(), packet_type);
            }
            1 => {
                let flag = kani::any();
                header.set_secondary_header_flag(flag);
                assert_eq!(header.secondary_header_flag(), flag);
            }
            2 => {
                let apid = Apid::any_apid();
                header.set_apid(apid);
                assert_eq!(header.apid(), apid);
            }
            3 => {
                let flag = kani::any();
                header.set_sequence_flag(flag);
                assert_eq!(header.sequence_flag(), flag);
            }
            _ => {
                let count = PacketSequenceCount::any_packet_sequence_count();
                header.set_packet_sequence_count(count);
                assert_eq!(header.packet_sequence_count(), count);
            }
        }

        // Every field that was not explicitly set must be unchanged. Comparing all fields of the
        // modified header against the original is equivalent, as at most one of them may differ.
        let differing = [
            header.packet_version() != original.packet_version(),
            header.packet_type() != original.packet_type(),
            header.secondary_header_flag() != original.secondary_header_flag(),
            header.apid() != original.apid(),
            header.sequence_flag() != original.sequence_flag(),
            header.packet_sequence_count() != original.packet_sequence_count(),
            header.packet_data_length() != original.packet_data_length(),
        ];
        assert!(differing.iter().filter(|differs| **differs).count() <= 1);
        assert_eq!(header.packet_version(), original.packet_version());
        assert_eq!(header.packet_data_length(), original.packet_data_length());
    }

    /// This test verifies that all (!) possible packet construction requests can be handled
    /// without panics when working with a fixed-size buffer that does not permit all possible
    /// packet size requests, that exactly the valid requests succeed, and that each constructed
    /// packet parses back to the requested header fields. Here, we do not touch the data field, to
    /// prevent exponential blow-up of the proof pipeline. Since the packet constructor performs no
    /// actions on the packet data field beyond returning a reference to it, this makes for a
    /// strong proof about the safety of this function.
    ///
    /// The buffer size is rather arbitrarily chosen to be 1024. This covers a significant amount
    /// of valid packet sizes, but also ensures that the "error path" is covered, where the
    /// requested packet is larger than the available buffer.
    #[kani::proof]
    fn packet_construction() {
        let mut bytes = [kani::any(); 1024];
        let packet_type = kani::any();
        let secondary_header_flag = kani::any();
        let apid = Apid::any_apid();
        let sequence_flag = kani::any();
        let sequence_count = PacketSequenceCount::any_packet_sequence_count();
        let buffer_length: usize = kani::any();
        kani::assume(buffer_length <= bytes.len());

        let packet = SpacePacket::construct(
            &mut bytes[..buffer_length],
            packet_type,
            secondary_header_flag,
            apid,
            sequence_flag,
            sequence_count,
        );

        // Exactly the valid requests must result in a returned packet.
        let valid_request = buffer_length > 6
            && !(apid.is_idle() && secondary_header_flag == SecondaryHeaderFlag::Present);
        assert_eq!(packet.is_ok(), valid_request);

        // Any returned packet must be consistent with the requested header information, and
        // parse back to the same packet.
        if let Ok(packet) = packet {
            assert_eq!(packet.packet_length(), buffer_length);
            assert_eq!(
                packet.packet_data_field().len(),
                packet.packet_data_length()
            );
            assert_eq!(packet.packet_type(), packet_type);
            assert_eq!(packet.secondary_header_flag(), secondary_header_flag);
            assert_eq!(packet.apid(), apid);
            assert_eq!(packet.sequence_flag(), sequence_flag);
            assert_eq!(packet.packet_sequence_count(), sequence_count);

            let parsed = SpacePacket::parse(packet.as_bytes());
            assert_eq!(parsed, Ok(&*packet));
        }
    }
}

